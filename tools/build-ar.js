// Builds the Arabic pages under /ar/ from the English pages at the root, so each language has its own URL
// that search engines can index (the hash link #ar never reached Google).
//
// Run after editing any page:   node tools/build-ar.js
//
// Every page already holds both languages (.en / .ar spans). The Arabic copy only changes what a crawler
// reads first: the <html> language and direction, the title, description, canonical URL and Open Graph tags,
// image alt text, and relative paths (one folder deeper). It also rewrites sitemap.xml with both languages.
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "ar");
const SITE = "https://ward00al-khatib.github.io/";
const TODAY = new Date().toISOString().slice(0, 10);

const PAGES = {
  "index.html": {
    title: "ورد الخطيب · مهندس ميكاترونيك وروبوتيك",
    desc: "ورد الخطيب، مهندس ميكاترونيك ومدرّب روبوتيك من سوريا. مشروع تخرجه WALL-E Junior روبوت ذاتي القيادة يفرز النفايات، ودرّب فريق H2A حتى فضية النهائي الدولي لأولمبياد الروبوت العالمي WRO 2023.",
    priority: "1.0",
  },
  "community.html": { title: "العمل المجتمعي · ورد الخطيب", priority: "0.7" },
  "competitions.html": { title: "تدريب فرق المسابقات · ورد الخطيب", priority: "0.7" },
  "teaching.html": { title: "التعليم والكورسات · ورد الخطيب", priority: "0.7" },
  "graduation.html": { title: "مشروع التخرج WALL-E Junior · ورد الخطيب", priority: "0.9" },
  "university.html": { title: "المشاريع الجامعية · ورد الخطيب", priority: "0.7" },
  "side-projects.html": { title: "المشاريع الجانبية · ورد الخطيب", priority: "0.7" },
  "awards.html": { title: "الإنجازات والجوائز · ورد الخطيب", priority: "0.7" },
};

const esc = (t) => t.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const plain = (h) => h.replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();
const urlOf = (pg, ar) => SITE + (ar ? "ar/" : "") + (pg === "index.html" ? "" : pg);

// the Arabic lead of a page, cut at a word near 165 characters, as its description
const arabicLead = (s) => {
  const m = s.match(/<p class="page-lead">[\s\S]*?<span class="ar">([\s\S]*?)<\/span><\/p>/);
  if (!m) return null;
  let t = plain(m[1]);
  if (t.length > 170) t = t.slice(0, t.lastIndexOf(" ", 165)).replace(/[،,:؛]$/, "") + "…";
  return t;
};

// one folder deeper: assets, images and files gain "../"; other pages stay relative to /ar/
const deeper = (v) => {
  if (/^(https?:|\/|#|mailto:|tel:|data:|javascript:)/i.test(v) || v === "") return v;
  if (/^[^/]+\.html(#.*)?$/.test(v)) return v;
  return "../" + v;
};

fs.mkdirSync(OUT, { recursive: true });
for (const [pg, meta] of Object.entries(PAGES)) {
  let s = fs.readFileSync(path.join(ROOT, pg), "utf8");
  const eol = /\r\n/.test(s) ? "\r\n" : "\n";
  const need = (re, label) => {
    if (!re.test(s)) throw new Error(`${pg}: missing ${label}`);
  };
  need(/data-url-lang="en"/, "data-url-lang");
  s = s.replace(/<html lang="en" dir="ltr" data-lang="en" data-url-lang="en">/, `<html lang="ar" dir="rtl" data-lang="ar" data-url-lang="ar">`);

  const desc = meta.desc || arabicLead(s);
  if (!desc) throw new Error(`${pg}: no Arabic description`);
  s = s.replace(/<title>[^<]*<\/title>/, `<title>${esc(meta.title)}</title>`);
  s = s.replace(/<meta name="description" content="[^"]*">/, `<meta name="description" content="${esc(desc)}">`);
  s = s.replace(/<meta property="og:title" content="[^"]*">/, `<meta property="og:title" content="${esc(meta.title)}">`);
  s = s.replace(/<meta property="og:description" content="[^"]*">/, `<meta property="og:description" content="${esc(desc)}">`);
  s = s.replace(/<meta property="og:url" content="[^"]*">/, `<meta property="og:url" content="${urlOf(pg, true)}">`);
  s = s.replace(/<meta property="og:locale" content="en_US">/, `<meta property="og:locale" content="ar_SY">`);
  s = s.replace(/<meta property="og:locale:alternate" content="ar_SY">/, `<meta property="og:locale:alternate" content="en_US">`);
  s = s.replace(/<link rel="canonical" href="[^"]*">/, `<link rel="canonical" href="${urlOf(pg, true)}">`);

  // relative paths, including every candidate in srcset
  s = s.replace(/\s(src|href|poster)="([^"]*)"/g, (m, a, v) => ` ${a}="${deeper(v)}"`);
  s = s.replace(/\ssrcset="([^"]*)"/g, (m, v) => ` srcset="${v.split(/,\s*/).map((c) => { const [u, d] = c.split(/\s+/); return deeper(u) + (d ? " " + d : ""); }).join(", ")}"`);

  // Arabic alt text first, for crawlers and for readers before site.js runs
  s = s.replace(/<img\b[^>]*>/g, (tag) => {
    const ar = tag.match(/\sdata-ar-alt="([^"]*)"/);
    return ar ? tag.replace(/\salt="[^"]*"/, ` alt="${ar[1]}"`) : tag;
  });

  s = s.replace(/<!doctype html>/i, (m) => `${m}${eol}<!-- generated by tools/build-ar.js from ../${pg}: edit the English page, then run node tools/build-ar.js -->`);
  fs.writeFileSync(path.join(OUT, pg), s);
  console.log(`ar/${pg}  ${meta.title}`);
}

// sitemap with both languages and their alternates
const rows = [];
for (const [pg, meta] of Object.entries(PAGES)) {
  for (const ar of [false, true]) {
    rows.push(`  <url>
    <loc>${urlOf(pg, ar)}</loc>
    <lastmod>${TODAY}</lastmod>
    <priority>${meta.priority}</priority>
    <xhtml:link rel="alternate" hreflang="en" href="${urlOf(pg, false)}"/>
    <xhtml:link rel="alternate" hreflang="ar" href="${urlOf(pg, true)}"/>
    <xhtml:link rel="alternate" hreflang="x-default" href="${urlOf(pg, false)}"/>
  </url>`);
  }
}
fs.writeFileSync(
  path.join(ROOT, "sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${rows.join("\n")}
</urlset>
`,
);
console.log(`sitemap.xml  ${rows.length} URLs`);
